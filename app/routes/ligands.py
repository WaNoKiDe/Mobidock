"""
routes/ligands.py — Ligand browser (PubChem search) and SMILES lookup by CID.
"""
import asyncio
import logging

from fastapi import APIRouter, HTTPException

from .. import pubchem

logger = logging.getLogger("medchem.ligands")
router = APIRouter()


def _search(query: str, max_results: int):
    names = pubchem.autocomplete(query, max_results) or [query]
    results = []
    for name in names[:max_results]:
        try:
            p = pubchem.fetch_properties("name", name, timeout=8)
        except Exception:
            continue
        if p and p["smiles"]:
            results.append(pubchem.result_card(name, p))
    if not results and names != [query]:
        try:
            p = pubchem.fetch_properties("name", query)
            if p and p["smiles"]:
                results.append(pubchem.result_card(query, p))
        except Exception as exc:
            logger.warning("Direct PubChem lookup failed: %s", exc)
    return results


@router.get("/api/ligand/search")
async def search_ligands(q: str, max_results: int = 8):
    """Search PubChem by compound name — returns cards with a guaranteed non-empty SMILES."""
    if not q or not q.strip():
        raise HTTPException(status_code=400, detail="Query is required")
    results = await asyncio.to_thread(_search, q.strip(), max(1, min(max_results, 15)))
    return {
        "query": q.strip(),
        "results": results,
        "warning": "" if results else "No matching dockable compounds were returned. Try a different name.",
    }


@router.get("/api/ligand/smiles/{cid}")
async def smiles_for_cid(cid: int):
    """Resolve a PubChem CID to SMILES (used if a card arrives without one)."""
    p = await asyncio.to_thread(pubchem.fetch_properties, "cid", cid)
    if not p or not p["smiles"]:
        raise HTTPException(status_code=404, detail=f"No SMILES available for CID {cid}")
    return {"cid": cid, "smiles": p["smiles"]}


@router.get("/api/pubchem/search")
async def search_pubchem(name: str):
    """Legacy: resolve a chemical name to one SMILES string."""
    if not name or not name.strip():
        raise HTTPException(status_code=400, detail="Name is required")
    try:
        p = await asyncio.to_thread(pubchem.fetch_properties, "name", name.strip())
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"PubChem error: {exc}")
    if not p or not p["smiles"]:
        raise HTTPException(status_code=404, detail="Molecule not found in PubChem")
    return {"name": name, "smiles": p["smiles"]}

