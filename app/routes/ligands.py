import math as _rdk_math
import re as _rdk_re
from fastapi import Body as _RDKBody
from rdkit import Chem as _RDKChem
from rdkit.Chem import (
    Crippen as _RDKCrippen,
    Descriptors as _RDKDescriptors,
    Lipinski as _RDKLipinski,
    QED as _RDKQED,
    rdMolDescriptors as _RDKMolDescriptors,
)


def _rdk_value(value):
    """Return finite, JSON-safe numeric values."""
    try:
        value = float(value)
    except (TypeError, ValueError):
        return None
    if not _rdk_math.isfinite(value):
        return None
    return int(value) if value.is_integer() else round(value, 5)


def _rdk_label(key):
    return _rdk_re.sub(r"(?<!^)([A-Z])", r" \1", str(key)).replace("_", " ").strip()


def _rdk_group(key):
    key = str(key).lower()
    if any(x in key for x in ("molwt", "exactmolwt", "logp", "mr", "tpsa", "fractioncsp3", "labuteasa")):
        return "Physicochemical"
    if any(x in key for x in ("donor", "acceptor", "rotatable", "ring", "heavyatom", "nhoh", "no_count", "charge")):
        return "Drug-likeness"
    if any(x in key for x in ("estate", "vsa", "slogp", "smr")):
        return "Surface / fragment"
    if any(x in key for x in ("chi", "kappa", "bertz", "balaban", "hallkier", "ipc", "bcut")):
        return "Topology"
    return "Other RDKit descriptors"


def _rdk_features(smiles):
    smiles = (smiles or "").strip()
    mol = _RDKChem.MolFromSmiles(smiles)
    if mol is None:
        raise ValueError("Not a valid SMILES string.")

    mw = _RDKDescriptors.MolWt(mol)
    logp = _RDKCrippen.MolLogP(mol)
    hbd = _RDKLipinski.NumHDonors(mol)
    hba = _RDKLipinski.NumHAcceptors(mol)

    summary = [
        {"key": "Formula", "label": "Molecular formula", "value": _RDKMolDescriptors.CalcMolFormula(mol), "unit": ""},
        {"key": "MolWt", "label": "Molecular weight", "value": _rdk_value(mw), "unit": "Da"},
        {"key": "ExactMolWt", "label": "Exact mass", "value": _rdk_value(_RDKDescriptors.ExactMolWt(mol)), "unit": "Da"},
        {"key": "MolLogP", "label": "cLogP", "value": _rdk_value(logp), "unit": ""},
        {"key": "MolMR", "label": "Molar refractivity", "value": _rdk_value(_RDKCrippen.MolMR(mol)), "unit": ""},
        {"key": "TPSA", "label": "Topological polar surface area", "value": _rdk_value(_RDKMolDescriptors.CalcTPSA(mol)), "unit": "Å²"},
        {"key": "NumHDonors", "label": "H-bond donors", "value": _rdk_value(hbd), "unit": ""},
        {"key": "NumHAcceptors", "label": "H-bond acceptors", "value": _rdk_value(hba), "unit": ""},
        {"key": "NumRotatableBonds", "label": "Rotatable bonds", "value": _rdk_value(_RDKLipinski.NumRotatableBonds(mol)), "unit": ""},
        {"key": "RingCount", "label": "Ring count", "value": _rdk_value(_RDKMolDescriptors.CalcNumRings(mol)), "unit": ""},
        {"key": "NumAromaticRings", "label": "Aromatic rings", "value": _rdk_value(_RDKMolDescriptors.CalcNumAromaticRings(mol)), "unit": ""},
        {"key": "FractionCSP3", "label": "Fraction Csp³", "value": _rdk_value(_RDKMolDescriptors.CalcFractionCSP3(mol)), "unit": ""},
        {"key": "HeavyAtomCount", "label": "Heavy atoms", "value": _rdk_value(_RDKDescriptors.HeavyAtomCount(mol)), "unit": ""},
        {"key": "FormalCharge", "label": "Formal charge", "value": _rdk_value(_RDKChem.GetFormalCharge(mol)), "unit": ""},
        {"key": "QED", "label": "QED drug-likeness", "value": _rdk_value(_RDKQED.qed(mol)), "unit": ""},
        {
            "key": "LipinskiViolations",
            "label": "Lipinski Rule-of-Five violations",
            "value": int((mw > 500) + (logp > 5) + (hbd > 5) + (hba > 10)),
            "unit": "",
        },
    ]

    descriptors = []
    desc_list = getattr(_RDKDescriptors, "_descList", getattr(_RDKDescriptors, "descList", []))
    for name, fn in desc_list:
        try:
            value = _rdk_value(fn(mol))
        except Exception:
            continue
        if value is not None:
            descriptors.append({
                "key": name,
                "label": _rdk_label(name),
                "value": value,
                "group": _rdk_group(name),
            })

    descriptors.sort(key=lambda row: (row["group"], row["label"]))

    return {
        "input_smiles": smiles,
        "canonical_smiles": _RDKChem.MolToSmiles(mol),
        "formula": _RDKMolDescriptors.CalcMolFormula(mol),
        "summary": summary,
        "descriptors": descriptors,
        "descriptor_count": len(descriptors),
    }


@router.get("/api/ligand/features")
async def rdkit_ligand_features(smiles: str):
    try:
        return _rdk_features(smiles)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc))


@router.post("/api/ligand/compare")
async def rdkit_ligand_compare(payload: dict = _RDKBody(...)):
    smiles_a = str(payload.get("smiles_a", "")).strip()
    smiles_b = str(payload.get("smiles_b", "")).strip()

    if not smiles_a or not smiles_b:
        raise HTTPException(status_code=422, detail="Provide both ligand SMILES strings.")

    try:
        left = _rdk_features(smiles_a)
        right = _rdk_features(smiles_b)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc))

    left_values = {row["key"]: row for row in left["descriptors"]}
    right_values = {row["key"]: row for row in right["descriptors"]}
    rows = []

    for key in sorted(set(left_values) | set(right_values)):
        a = left_values.get(key, {})
        b = right_values.get(key, {})
        av, bv = a.get("value"), b.get("value")
        delta = round(bv - av, 5) if isinstance(av, (int, float)) and isinstance(bv, (int, float)) else None
        rows.append({
            "key": key,
            "label": a.get("label") or b.get("label") or _rdk_label(key),
            "group": a.get("group") or b.get("group") or _rdk_group(key),
            "a": av,
            "b": bv,
            "delta": delta,
        })

    return {"a": left, "b": right, "rows": rows}
